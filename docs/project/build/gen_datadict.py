#!/usr/bin/env python3
"""Generate the data dictionary appendix (Markdown) straight from supabase/migrations/*.sql.
Usage: gen_datadict.py <migrations_dir> <out.md>"""
import re, sys, pathlib
mig = pathlib.Path(sys.argv[1]); out = pathlib.Path(sys.argv[2])
def split_top(s):
    parts, depth, cur = [], 0, ''
    for ch in s:
        if ch == '(': depth += 1
        elif ch == ')': depth -= 1
        if ch == ',' and depth == 0: parts.append(cur); cur = ''
        else: cur += ch
    if cur.strip(): parts.append(cur)
    return parts
def body_after(sql, start):
    depth = 0
    for i in range(start, len(sql)):
        if sql[i] == '(': depth += 1
        elif sql[i] == ')':
            depth -= 1
            if depth == 0: return sql[start+1:i]
    return ''
lines = ["<!-- generated by build/gen_datadict.py from supabase/migrations; do not edit by hand -->", ""]
for f in sorted(mig.glob('*.sql')):
    sql = re.sub(r'--[^\n]*', '', f.read_text())
    tables = []
    for m in re.finditer(r'create table if not exists ([a-z_]+\.[a-z_]+)\s*\(', sql, re.I):
        cols = []
        for part in split_top(body_after(sql, m.end()-1)):
            p = ' '.join(part.split())
            if not p or re.match(r'(primary key|unique|constraint|check|foreign key|exclude)\b', p, re.I): continue
            mm = re.match(r'"?([a-z_0-9]+)"?\s+(.*)', p, re.I)
            if not mm: continue
            name, rest = mm.groups()
            typ = re.split(r'\s+(not null|null|default|primary|references|check|unique|generated|constraint)\b', rest, 1, flags=re.I)[0]
            notes = rest[len(typ):].strip()
            notes = re.sub(r'\s+', ' ', notes)[:110].replace('|', '\\|')
            cols.append((name, typ.strip().replace('|','\\|'), notes))
        tables.append((m.group(1), cols))
    adds = re.findall(r'alter table (?:if exists )?(?:only )?([a-z_]+\.[a-z_]+)\s+((?:add column if not exists [^;]+?)(?:,\s*add column if not exists [^;]+?)*);', sql, re.I)
    views = re.findall(r'create (?:or replace )?view ([a-z_]+\.[a-z_]+)', sql, re.I)
    fns = sorted(set(re.findall(r'create (?:or replace )?function ([a-z_]+\.[a-z_]+)', sql, re.I)))
    rls = sorted(set(re.findall(r'alter table ([a-z_]+\.[a-z_]+) enable row level security', sql, re.I)))
    buckets = sorted(set(re.findall(r"insert into storage\.buckets[^;]*?values\s*\(\s*'([a-z_-]+)'", sql, re.I)))
    lines += [f"## {f.name}", ""]
    if not (tables or adds or views or fns): lines += ["Grant / configuration change only (no new tables or functions).", ""]
    for t, cols in tables:
        lines += [f"### Table `{t}`", "", "| Column | Type | Constraints / default |", "|---|---|---|"]
        lines += [f"| `{c}` | {ty} | {n} |" for c, ty, n in cols] + [""]
    for t, clause in adds:
        cs = re.findall(r'add column if not exists ([a-z_0-9]+)\s+([^,]+)', clause, re.I)
        if cs:
            lines += [f"**Columns added to `{t}`:** " + ", ".join(f"`{c}` ({ty.strip()[:40]})" for c, ty in cs), ""]
    if views: lines += ["**Views:** " + ", ".join(f"`{v}`" for v in sorted(set(views))), ""]
    if rls: lines += ["**RLS enabled (explicit in this file):** " + ", ".join(f"`{r}`" for r in rls), ""]
    if buckets: lines += ["**Storage buckets:** " + ", ".join(f"`{b}`" for b in buckets), ""]
    if fns: lines += ["**Functions / RPCs:** " + ", ".join(f"`{x}`" for x in fns), ""]
out.write_text('\n'.join(lines))
print(out, len(lines), 'lines')
