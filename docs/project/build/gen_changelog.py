#!/usr/bin/env python3
"""Regenerate md/_changelog.md (full commit list for 18 Release Notes) from git when a repository is available.
Usage: gen_changelog.py <repo_dir> [rev]   (default rev: HEAD). Times are shown in the commit's own zone (ET)."""
import subprocess, sys, pathlib, html
repo = sys.argv[1]; rev = sys.argv[2] if len(sys.argv) > 2 else "HEAD"
out = pathlib.Path(__file__).resolve().parent.parent / "md" / "_changelog.md"
log = subprocess.run(["git", "-C", repo, "log", "--reverse", "--no-merges", "--format=%h%x09%ad%x09%s", "--date=format:%Y-%m-%d %H:%M", rev],
                     capture_output=True, text=True, check=True).stdout.strip().splitlines()
merges = subprocess.run(["git", "-C", repo, "log", "--merges", "--format=%h%x09%ad%x09%s", "--date=format:%Y-%m-%d %H:%M", rev],
                        capture_output=True, text=True, check=True).stdout.strip().splitlines()
L = ["<!-- generated by build/gen_changelog.py from git; do not edit by hand -->", "",
     f"{len(log)} non-merge commits and {len(merges)} merge commits up to `{rev}`.", "",
     "| # | Commit | Date / time (ET) | Change |", "|---|---|---|---|"]
for i, line in enumerate(log, 1):
    h, d, s = line.split("\t", 2)
    s = s.replace("|", "\\|")
    L.append(f"| {i} | `{h}` | {d} | {s} |")
L += ["", "Merge commits:", "", "| Commit | Date / time (ET) | Merge |", "|---|---|---|"]
for line in merges:
    h, d, s = line.split("\t", 2); L.append(f"| `{h}` | {d} | {s.replace('|', chr(92) + '|')} |")
out.write_text("\n".join(L) + "\n"); print(out, len(log), "commits")
