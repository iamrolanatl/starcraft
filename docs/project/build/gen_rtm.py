sett(["FR-056"], "T-023, T-024"); sett(["FR-058"], "T-048"); sett(["FR-059"], "T-001"); sett(rng(61, 85), "T-047")
sett(rng(62, 63), "T-002, T-047"); sett(["FR-065"], "T-003"); sett(["FR-081"], "T-007, T-047"); sett(["FR-085"], "T-021")
