#!/usr/bin/env python3
"""Generate the traceability tables for 14 RTM (md/_rtm.md) from 03 BRD, 04 FRS, 05 NFR and 08 Feature Catalog,
so IDs, titles and statuses never drift between documents. Mappings that are judgement calls live in this file."""
import re, pathlib
MD = pathlib.Path(__file__).resolve().parent.parent / "md"
def rows(fname, prefix):
    out = {}
    for line in (MD / fname).read_text().splitlines():
        m = re.match(rf"^\| ({prefix}-\d+) \| (.*)$", line)
        if m:
            cells = [c.strip() for c in m.group(2).split(" | ")]
            st = re.findall(r"\[\[(ok|partial|no)\|([^\]]+)\]\]", line)
            out[m.group(1)] = (cells, st[-1] if st else ("", ""))
    return out
def rng(a, b): return [f"FR-{i:03d}" for i in range(a, b + 1)]
BR_OF = {}
def setbr(frs, br):
    for f in frs: BR_OF[f] = br
setbr(rng(1, 12), "BR-001"); setbr(rng(13, 30), "BR-013"); setbr(rng(31, 36), "BR-007"); setbr(rng(37, 39), "BR-013")
setbr(["FR-040"], "BR-007"); setbr(rng(41, 42), "BR-017"); setbr(rng(43, 60), "BR-014"); setbr(rng(53, 54), "BR-009")
setbr(["FR-056"], "BR-008"); setbr(rng(61, 85), "BR-002"); setbr(["FR-064", "FR-066"], "BR-016"); setbr(["FR-073"], "BR-008")
setbr(["FR-080"], "BR-009"); setbr(["FR-085"], "BR-004"); setbr(rng(86, 87), "BR-003"); setbr(["FR-088"], "BR-006")
setbr(rng(89, 90), "BR-004"); setbr(rng(91, 93), "BR-005"); setbr(["FR-094"], "BR-002"); setbr(rng(95, 96), "BR-004")
