sett(rng(111, 112), "T-047"); sett(rng(113, 114), "Demonstration (after 018)"); sett(rng(115, 120), "T-022"); sett(["FR-121"], "T-021")
sett(["FR-122"], "T-047"); sett(rng(123, 135), "T-021"); sett(rng(136, 138), "T-030"); sett(["FR-139"], "T-050"); sett(["FR-140"], "—")
brd = rows("03_Business_Requirements.md", "BR"); fr = rows("04_Functional_Requirements.md", "FR"); nfr = rows("05_Non_Functional_Requirements.md", "NFR")
feat = rows("08_Feature_Catalog.md", "F")
FEAT_OF = {}
for fid, (cells, _) in feat.items():
    spec = cells[3] if len(cells) > 3 else ""
    nums = []
    for part in re.sub(r"FR-", "", spec).split(","):
        part = part.strip()
        m = re.match(r"(\d+)\s*[–-]\s*(\d+)", part)
        if m: nums += list(range(int(m.group(1)), int(m.group(2)) + 1))
        elif re.match(r"^\d+", part): nums.append(int(re.match(r"\d+", part).group(0)))
    for n in nums: FEAT_OF.setdefault(f"FR-{n:03d}", []).append(fid)
PILL = lambda st: f"[[{st[0]}|{st[1]}]]" if st[0] else ""
L = ["<!-- generated by build/gen_rtm.py; do not edit by hand -->", ""]
L += ["### Business requirement → objective → functional requirements", "", "| BR | Business requirement | Objective(s) | Priority | Functional requirements |", "|---|---|---|---|---|"]
for br, (cells, _) in brd.items():
    frs = [f for f in sorted(BR_OF) if BR_OF[f] == br]
    def compress(ids):
        n = [int(x[3:]) for x in ids]; out = []; i = 0
        while i < len(n):
            j = i
            while j + 1 < len(n) and n[j + 1] == n[j] + 1: j += 1
            out.append(f"FR-{n[i]:03d}" + (f"–{n[j]:03d}" if j > i else "")); i = j + 1
        return ", ".join(out)
    L.append(f"| {br} | {cells[0]} | {cells[1]} | {cells[2]} | {compress(frs) or '—'} |")
L += ["", "### Functional requirement forward trace", "", "| FR | Requirement (short) | BR | BO | Feature(s) | Verification | Status |", "|---|---|---|---|---|---|---|"]
bo_of_br = {br: cells[1] for br, (cells, _) in brd.items()}
for f, (cells, st) in fr.items():
    title = re.sub(r"^Crystal shall |^The |^A |^An ", "", cells[0]); title = title[:95] + ("…" if len(title) > 95 else "")
    br = BR_OF.get(f, "—")
    L.append(f"| {f} | {title} | {br} | {bo_of_br.get(br, '—')} | {', '.join(FEAT_OF.get(f, [])) or '—'} | {T.get(f, '—')} | {PILL(st)} |")
NBO = {}
for i in range(1, 16): NBO[f"NFR-{i:03d}"] = "BO-04"
for i in range(16, 20): NBO[f"NFR-{i:03d}"] = "BO-04"
NBO.update({"NFR-020": "BO-02", "NFR-021": "BO-03", "NFR-022": "BO-02, BO-05"})
for i in range(23, 27): NBO[f"NFR-{i:03d}"] = "BO-01"
for i in range(27, 37): NBO[f"NFR-{i:03d}"] = "BO-09"
for i in range(37, 50): NBO[f"NFR-{i:03d}"] = "BO-01"
NBO["NFR-050"] = "BO-07"
for i in range(51, 59): NBO[f"NFR-{i:03d}"] = "BO-09"
NBO["NFR-054"] = "BO-07"
for i in range(59, 62): NBO[f"NFR-{i:03d}"] = "BO-04"
NT = {"NFR-001": "T-020, T-021, T-022", "NFR-002": "Inspection", "NFR-003": "Inspection", "NFR-004": "Inspection", "NFR-005": "T-021, Inspection",
      "NFR-006": "Inspection", "NFR-007": "T-047 (H1), T-040", "NFR-008": "T-040", "NFR-009": "T-050", "NFR-010": "T-022, T-050", "NFR-011": "T-022",
      "NFR-012": "T-021", "NFR-013": "T-047", "NFR-014": "Inspection", "NFR-015": "T-021", "NFR-016": "T-020, T-021", "NFR-017": "Inspection",
      "NFR-018": "Inspection", "NFR-019": "Inspection", "NFR-020": "M-13 measurement", "NFR-021": "Analysis; M-13", "NFR-022": "Inspection (crontab)",
      "NFR-023": "Inspection", "NFR-024": "T-046", "NFR-025": "T-040", "NFR-026": "T-045", "NFR-027": "Demonstration", "NFR-028": "T-030",
      "NFR-029": "T-027", "NFR-030": "T-027, T-021", "NFR-031": "T-025, T-028", "NFR-032": "T-027", "NFR-033": "T-050", "NFR-034": "T-040",
      "NFR-035": "T-040", "NFR-036": "Analysis", "NFR-037": "T-043", "NFR-038": "T-041", "NFR-039": "T-044", "NFR-040": "T-040, Inspection",
      "NFR-041": "T-040", "NFR-042": "Demonstration", "NFR-043": "T-046", "NFR-044": "T-044, T-040", "NFR-045": "T-044", "NFR-046": "T-011, T-044",
      "NFR-047": "Inspection", "NFR-048": "T-042", "NFR-049": "T-051", "NFR-050": "Demonstration", "NFR-051": "T-020, T-021", "NFR-052": "T-009, T-010",
      "NFR-053": "T-009", "NFR-054": "T-030", "NFR-055": "Inspection", "NFR-056": "Inspection", "NFR-057": "Inspection", "NFR-058": "Demonstration",
      "NFR-059": "Inspection", "NFR-060": "T-047", "NFR-061": "Inspection"}
L += ["", "### Non-functional requirement trace", "", "| NFR | Requirement (short) | BO | Verification | Compliance |", "|---|---|---|---|---|"]
for n, (cells, st) in nfr.items():
    title = cells[0][:100] + ("…" if len(cells[0]) > 100 else "")
    L.append(f"| {n} | {title} | {NBO.get(n, '—')} | {NT.get(n, '—')} | {PILL(st)} |")
cnt = {"ok": 0, "partial": 0, "no": 0}
for f, (_, st) in fr.items(): cnt[st[0]] = cnt.get(st[0], 0) + 1
untested = [f for f in fr if T.get(f, "—") == "—"]
nofeat = [f for f in fr if f not in FEAT_OF]
L += ["", "### Coverage summary", "", "| Measure | Value |", "|---|---|",
      f"| Functional requirements | {len(fr)} |", f"| FR status Done / Partial / Open-Won't | {cnt['ok']} / {cnt['partial']} / {cnt['no']} |",
      f"| FRs without a verification method | {len(untested)} ({', '.join(untested) or 'none'}) |",
      f"| FRs not linked to a catalogued feature | {len(nofeat)} ({', '.join(nofeat) or 'none'}) |",
      f"| Non-functional requirements | {len(nfr)} |", f"| Business requirements | {len(brd)} |", f"| Features | {len(feat)} |"]
(MD / "_rtm.md").write_text("\n".join(L) + "\n")
print("nofeat", nofeat); print("rtm:", len(fr), "FR", len(nfr), "NFR", len(brd), "BR", len(feat), "features; untested", untested, "nofeat", len(nofeat))
