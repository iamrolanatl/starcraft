setbr(rng(115, 121), "BR-011"); setbr(["FR-122"], "BR-012"); setbr(rng(123, 140), "BR-010"); setbr(["FR-129", "FR-136"], "BR-004")
setbr(["FR-132"], "BR-003"); setbr(["FR-001", "FR-004", "FR-005", "FR-006", "FR-011"], "BR-018"); setbr(["FR-012"], "BR-013")
T = {}
def sett(frs, t):
    for f in frs: T[f] = t
sett(rng(1, 12), "T-047"); sett(["FR-007", "FR-008"], "T-004"); sett(["FR-010", "FR-012"], "T-040"); sett(["FR-011"], "Inspection")
sett(["FR-013"], "T-040"); sett(["FR-014", "FR-015"], "T-041"); sett(rng(16, 18), "T-047"); sett(rng(19, 21), "T-042, T-040")
